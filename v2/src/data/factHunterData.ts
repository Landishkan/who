// ===== ИНТЕРФЕЙСЫ =====
export interface TrainingNewsItem {
  id: number;
  title: string;
  source: string;
  analysis: string[]; // Пункты разбора (почему это фейк)
  discussion: string; // Вопрос для обсуждения с классом
}

export interface NewsItem {
  id: number;
  title: string;
  source: string;
  isReal: boolean;
  flags: string[]; // Красные флаги (если это фейк)
}

export interface Level {
  id: number;
  condition: 'find-real' | 'find-fake'; // 'Найди правду' или 'Найди фейк'
  news: NewsItem[]; // Всегда 3 новости
  correctIndex: number; // 0, 1 или 2. Если isTrapLevel = true, это поле игнорируется
  isTrapLevel: boolean; // Если true, правильный ответ — специальная кнопка
  specialButtonText: string; // Текст кнопки-ловушки (например, "🛡️ Тут нет фейковой новости")
}

export interface Category {
  id: string;
  name: string;
  icon: string; // Название иконки из lucide-react
  levels: Level[];
}

